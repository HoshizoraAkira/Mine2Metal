#!/bin/sh
# Builds the FSR shaders the game uses and embeds them as C for the dylib (src/main/native/fsr/fsr_shaders.h):
# optical flow, frame interpolation for motion vectors at render and at display resolution, and the FSR 3.1 (motion
# vectors at render resolution) and FSR 1 upscalers.
#   scripts/build-fsr-embedded.sh <output directory>, which gets fsr_shaders.c
set -eu
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$1"
rm -rf "$OUT/full" "$OUT/lowres" "$OUT/upscale"
FSR_EFFECTS="frameinterpolation opticalflow" FSR_LOW_RES_MOTION_VECTORS=0 "$ROOT/scripts/build-fsr-shaders.sh" "$OUT/full" > /dev/null
FSR_EFFECTS="frameinterpolation" FSR_LOW_RES_MOTION_VECTORS=1 "$ROOT/scripts/build-fsr-shaders.sh" "$OUT/lowres" > /dev/null
FSR_EFFECTS="fsr3upscaler fsr1" FSR_LOW_RES_MOTION_VECTORS=1 "$ROOT/scripts/build-fsr-shaders.sh" "$OUT/upscale" > /dev/null

{
	echo "// Generated by scripts/build-fsr-embedded.sh from the shaders of AMD FidelityFX SDK v1.1.4"
	echo "// (MIT, see third_party/fidelityfx-1.1.4/LICENSE.txt)."
	echo '#include "fsr_shaders.h"'
	index=0
	entries=""
	for spec in "$OUT/full/msl:" "$OUT/lowres/msl:@lowres" "$OUT/upscale/msl:"; do
		directory="${spec%%:*}"
		suffix="${spec#*:}"
		for file in "$directory"/*.metal; do
			echo "static const unsigned char shader$index[] = {"
			xxd -i < "$file"
			echo ", 0x00};"
			entries="$entries	{\"$(basename "$file" .metal)$suffix\", (const char *)shader$index},
"
			index=$((index + 1))
		done
	done
	printf 'const M2MFsrShader m2m_fsr_shaders[] = {\n%s};\n' "$entries"
	echo "const size_t m2m_fsr_shader_count = $index;"
} > "$OUT/fsr_shaders.c"
echo "Embedded $(grep -c '^static const unsigned char' "$OUT/fsr_shaders.c") FSR shaders into $OUT/fsr_shaders.c"
